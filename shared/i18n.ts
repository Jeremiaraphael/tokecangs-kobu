const DICTS: Record<Locale, Dict> = { en, id };

/** Keys missing from a language, or whose placeholders differ from English (used by tests). */
export function translationProblems(locale: Locale): string[] {
  const names = (t: string) => [...t.matchAll(/\{(\w+)/g)].map((m) => m[1]).sort().join(',');
  return Object.keys(en).flatMap((key) => {
    const other = DICTS[locale][key];
    if (other === undefined) return [`missing: ${key}`];
    return names(other) === names(en[key]) ? [] : [`placeholders differ: ${key}`];
  });
}

/** Translate a key (or a nested message) into the given language. */
export function translate(locale: Locale, key: string, params: Record<string, MsgParam> = {}): string {
  const template = DICTS[locale][key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)(?::(\w+))?(?:\|([^|}]*)\|([^}]*))?\}/g, (_m, name: string, fmt?: string, one?: string, many?: string) => {
    const value = params[name];
    if (value === undefined) return '';
    if (typeof value === 'object') return translate(locale, value.key, value.params);
    if (fmt === 'a') return rankWithArticle(locale, value as Rank);
    if (fmt === 'name') return rankName(locale, value as Rank);
    if (one !== undefined) return `${value} ${Number(value) === 1 ? one : many}`;
    return String(value);
  });
}

export const translateMsg = (locale: Locale, m: Msg) => translate(locale, m.key, m.params);
export const powerName = (locale: Locale, p: Power) => translate(locale, `power.${p}.name`);

