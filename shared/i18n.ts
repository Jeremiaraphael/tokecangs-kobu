import type { Power, Rank } from './cards';

export type Locale = 'en' | 'id';
export const LOCALES: Locale[] = ['en', 'id'];

/** A translatable message: key + params (params may themselves be messages). */
export interface Msg {
  key: string;
  params?: Record<string, MsgParam>;
}
export type MsgParam = string | number | Msg;
export const msg = (key: string, params?: Record<string, MsgParam>): Msg => ({ key, params });

const RANK_NAMES: Record<Locale, Partial<Record<Rank, string>>> = {
  en: { A: 'Ace', J: 'Jack', Q: 'Queen', K: 'King', JOKER: 'Joker' },
  id: { A: 'As', J: 'Jack', Q: 'Queen', K: 'King', JOKER: 'Joker' },
};

export function rankName(locale: Locale, rank: Rank): string {
  return RANK_NAMES[locale][rank] ?? rank;
}
function rankWithArticle(locale: Locale, rank: Rank): string {
  const name = rankName(locale, rank);
  if (locale === 'id') return name;
  return `${/^(Ace|8)/.test(name) ? 'an' : 'a'} ${name}`;
}

