/** Error messages with values in them. */
const ERROR_PATTERNS_ID: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^Need at least (\d+) players$/, (m) => `Butuh minimal ${m[1]} pemain`],
  [/^Room is full \(max (\d+)\)$/, (m) => `Ruangan penuh (maks. ${m[1]})`],
  [/^You may only peek at (\d+) cards?$/, (m) => `Kamu hanya boleh mengintip ${m[1]} kartu`],
  [/^Peek at (\d+) cards? first$/, (m) => `Intip ${m[1]} kartu dulu`],
  [/^(.+) is still connected$/, (m) => `${m[1]} masih terhubung`],
];

/** Translate an error message from the server (they are sent in English). */
export function translateError(locale: Locale, message: string): string {
  if (locale === 'en') return message;
  if (ERRORS_ID[message]) return ERRORS_ID[message];
  for (const [re, toId] of ERROR_PATTERNS_ID) {
    const m = message.match(re);
    if (m) return toId(m);
  }
  return message;
}
